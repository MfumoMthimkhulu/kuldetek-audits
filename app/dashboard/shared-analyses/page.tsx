"use client";
import { orionFetch } from "@/lib/orion-fetch";
import React, { useState, useEffect } from "react";
import { useRouter } from "next/navigation";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import {
  MdVisibility,
  MdEdit,
  MdComment,
  MdDownload,
  MdShare,
} from "react-icons/md";
import { toast } from "sonner";
import { createClient } from "@/utils/supabase/client";
import jsPDF from "jspdf";

export default function SharedAnalyses() {
  const router = useRouter();
  const supabase = createClient();
  const [sharedAnalyses, setSharedAnalyses] = useState([]);
  const [isLoading, setIsLoading] = useState(true);

  useEffect(() => {
    loadSharedAnalyses();
  }, []);

  const loadSharedAnalyses = async () => {
    try {
      const {
        data: { user },
      } = await supabase.auth.getUser();
      if (!user) {
        router.push("/sign-in");
        return;
      }

      // Get analyses shared with the current user
      const { data: shares, error: sharesError } = await supabase
        .from("analysis_shares")
        .select(
          `
          id,
          permission_level,
          shared_at,
          expires_at,
          is_active,
          audit_analysis!inner (
            id,
            audit_id,
            analysis_type,
            results,
            created_at,
            audits!inner (
              title,
              category,
              date,
              auditor
            ),
            profiles!audit_analysis_created_by_fkey (
              full_name,
              email
            )
          )
        `
        )
        .eq("shared_with_user_id", user.id)
        .eq("is_active", true)
        .gt("expires_at", new Date().toISOString())
        .order("shared_at", { ascending: false });

      if (sharesError) throw sharesError;

      setSharedAnalyses(shares || []);
    } catch (error) {
      console.error("Error loading shared analyses:", error);
      toast.error("Failed to load shared analyses");
    } finally {
      setIsLoading(false);
    }
  };

  const getPermissionIcon = (permission) => {
    switch (permission) {
      case "view":
        return <MdVisibility className="w-4 h-4" />;
      case "edit":
        return <MdEdit className="w-4 h-4" />;
      case "comment":
        return <MdComment className="w-4 h-4" />;
      default:
        return <MdVisibility className="w-4 h-4" />;
    }
  };

  const getPermissionColor = (permission) => {
    switch (permission) {
      case "view":
        return "bg-blue-500/10 text-blue-400 border-blue-500/20";
      case "edit":
        return "bg-green-500/10 text-green-400 border-green-500/20";
      case "comment":
        return "bg-purple-500/10 text-purple-400 border-purple-500/20";
      default:
        return "bg-gray-500/10 text-gray-400 border-gray-500/20";
    }
  };

  const viewAnalysis = async (analysis) => {
    // Mark related notifications as read
    try {
      const response = await orionFetch("/api/notifications", {
        method: "PUT",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          markAllAsRead: true,
        }),
      });
    } catch (error) {
      console.error("Error marking notifications as read:", error);
    }

    const encodedData = encodeURIComponent(JSON.stringify(analysis.results));
    router.push(
      `/dashboard/analysis-results?type=${analysis.analysis_type}&data=${encodedData}&auditId=${analysis.audit_id}&shared=true`
    );
  };

  const generatePDF = (analysis) => {
    if (!analysis.results || analysis.results.length === 0) {
      toast.error("No analysis data to export.");
      return;
    }

    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();
    const margin = 20;
    let yPosition = margin;

    // Title
    doc.setFontSize(20);
    doc.setFont("helvetica", "bold");
    doc.text(
      `${
        analysis.analysis_type.charAt(0).toUpperCase() +
        analysis.analysis_type.slice(1)
      } Analysis Report`,
      margin,
      yPosition
    );
    yPosition += 20;

    // Audit info
    doc.setFontSize(12);
    doc.setFont("helvetica", "normal");
    doc.text(`Audit: ${analysis.audits.title}`, margin, yPosition);
    yPosition += 5;
    doc.text(`Category: ${analysis.audits.category}`, margin, yPosition);
    yPosition += 5;
    doc.text(`Date: ${analysis.audits.date}`, margin, yPosition);
    yPosition += 5;
    doc.text(`Auditor: ${analysis.audits.auditor}`, margin, yPosition);
    yPosition += 5;
    doc.text(
      `Generated by: ${analysis.profiles.full_name || analysis.profiles.email}`,
      margin,
      yPosition
    );
    yPosition += 5;
    doc.text(
      `Generated on: ${new Date(analysis.created_at).toLocaleDateString()}`,
      margin,
      yPosition
    );
    yPosition += 15;

    // Analysis content
    analysis.results.forEach((item, index) => {
      // Check if we need a new page
      if (yPosition > doc.internal.pageSize.getHeight() - 40) {
        doc.addPage();
        yPosition = margin;
      }

      // Section title
      doc.setFontSize(14);
      doc.setFont("helvetica", "bold");
      const title = `${item.icon} ${item.metric}`;
      doc.text(title, margin, yPosition);
      yPosition += 10;

      // Content
      doc.setFontSize(10);
      doc.setFont("helvetica", "normal");

      if (item.isStructured) {
        const lines = item.value.split("\n");
        lines.forEach((line) => {
          if (yPosition > doc.internal.pageSize.getHeight() - 20) {
            doc.addPage();
            yPosition = margin;
          }
          const cleanLine = line.replace(/^• /, "• ");
          doc.text(cleanLine, margin + 10, yPosition);
          yPosition += 5;
        });

        if (item.observation) {
          yPosition += 5;
          if (yPosition > doc.internal.pageSize.getHeight() - 20) {
            doc.addPage();
            yPosition = margin;
          }
          doc.setFont("helvetica", "bold");
          doc.text("Observation:", margin + 10, yPosition);
          yPosition += 5;
          doc.setFont("helvetica", "normal");
          doc.text(item.observation, margin + 10, yPosition);
          yPosition += 5;
        }
      } else {
        const textLines = doc.splitTextToSize(
          item.value,
          pageWidth - 2 * margin - 20
        );
        textLines.forEach((line) => {
          if (yPosition > doc.internal.pageSize.getHeight() - 20) {
            doc.addPage();
            yPosition = margin;
          }
          doc.text(line, margin + 10, yPosition);
          yPosition += 5;
        });
      }

      yPosition += 10;
    });

    // Save the PDF
    doc.save(
      `shared-analysis-${
        analysis.analysis_type
      }-${analysis.audits.title.replace(/[^a-zA-Z0-9]/g, "_")}.pdf`
    );
    toast.success("PDF exported successfully!");
  };

  if (isLoading) {
    return (
      <div className="dashboard-container p-6">
        <main className="main-content">
          <Card className="bg-[#1e293b] border-[#334155]">
            <CardContent className="p-6 text-center">
              <p className="text-gray-300">Loading shared analyses...</p>
            </CardContent>
          </Card>
        </main>
      </div>
    );
  }

  return (
    <div className="dashboard-container p-6">
      <main className="main-content">
        <div className="dashboard-header mb-6">
          <div>
            <h2 className="header-title">Shared Analyses</h2>
            <p className="header-subtitle">
              View analyses shared with you by other users
            </p>
          </div>
        </div>

        {sharedAnalyses.length === 0 ? (
          <Card className="bg-[#1e293b] border-[#334155]">
            <CardContent className="p-6 text-center">
              <MdShare className="w-16 h-16 text-gray-400 mx-auto mb-4" />
              <h3 className="text-lg font-semibold text-white mb-2">
                No Shared Analyses
              </h3>
              <p className="text-gray-300">
                You don&apos;t have any analyses shared with you yet.
              </p>
            </CardContent>
          </Card>
        ) : (
          <div className="grid gap-6">
            {sharedAnalyses.map((share) => {
              const analysis = share.audit_analysis;
              return (
                <Card key={share.id} className="bg-[#1e293b] border-[#334155]">
                  <CardHeader>
                    <div className="flex justify-between items-start">
                      <div>
                        <CardTitle className="text-white flex items-center gap-2">
                          {analysis.audits.title}
                        </CardTitle>
                        <p className="text-gray-300 text-sm mt-1">
                          {analysis.analysis_type.charAt(0).toUpperCase() +
                            analysis.analysis_type.slice(1)}{" "}
                          Analysis
                        </p>
                      </div>
                      <Badge
                        className={getPermissionColor(share.permission_level)}
                      >
                        <div className="flex items-center gap-1">
                          {getPermissionIcon(share.permission_level)}
                          {share.permission_level}
                        </div>
                      </Badge>
                    </div>
                  </CardHeader>
                  <CardContent>
                    <div className="grid grid-cols-1 md:grid-cols-2 gap-4 mb-4">
                      <div className="space-y-2">
                        <div className="flex justify-between">
                          <span className="text-gray-300">Category:</span>
                          <span className="text-white">
                            {analysis.audits.category}
                          </span>
                        </div>
                        <div className="flex justify-between">
                          <span className="text-gray-300">Date:</span>
                          <span className="text-white">
                            {analysis.audits.date}
                          </span>
                        </div>
                        <div className="flex justify-between">
                          <span className="text-gray-300">Auditor:</span>
                          <span className="text-white">
                            {analysis.audits.auditor}
                          </span>
                        </div>
                      </div>
                      <div className="space-y-2">
                        <div className="flex justify-between">
                          <span className="text-gray-300">Shared by:</span>
                          <span className="text-white">
                            {analysis.profiles.full_name ||
                              analysis.profiles.email}
                          </span>
                        </div>
                        <div className="flex justify-between">
                          <span className="text-gray-300">Shared on:</span>
                          <span className="text-white">
                            {new Date(share.shared_at).toLocaleDateString()}
                          </span>
                        </div>
                        {share.expires_at && (
                          <div className="flex justify-between">
                            <span className="text-gray-300">Expires:</span>
                            <span className="text-white">
                              {new Date(share.expires_at).toLocaleDateString()}
                            </span>
                          </div>
                        )}
                      </div>
                    </div>

                    <div className="flex gap-2">
                      <Button
                        onClick={() => viewAnalysis(analysis)}
                        className="bg-cyan-600 hover:bg-cyan-700 text-white"
                      >
                        <MdVisibility className="w-4 h-4 mr-2" />
                        View Analysis
                      </Button>
                      <Button
                        onClick={() => generatePDF(analysis)}
                        variant="outline"
                        className="border-[#334155] text-gray-300 hover:bg-[#334155]"
                      >
                        <MdDownload className="w-4 h-4 mr-2" />
                        Export PDF
                      </Button>
                    </div>
                  </CardContent>
                </Card>
              );
            })}
          </div>
        )}
      </main>
    </div>
  );
}
